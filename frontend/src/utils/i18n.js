const getByPath = (obj, path) => {
  if (!obj) return undefined;
  const parts = String(path || '').split('.').filter(Boolean);
  let cursor = obj;
  for (const part of parts) {
    if (cursor && Object.prototype.hasOwnProperty.call(cursor, part)) {
      cursor = cursor[part];
    } else {
      return undefined;
    }
  }
  return cursor;
};

const interpolate = (value, params) => {
  if (typeof value !== 'string') return value;
  if (!params) return value;
  return value.replace(/\{(\w+)\}/g, (_, key) => {
    const v = params[key];
    return v === undefined || v === null ? '' : String(v);
  });
};

export const tFor = (preferredLanguage, key, params) => {
  const lang = normalizePreferredLanguage(preferredLanguage);
  const base = TRANSLATIONS.english;
  const active = TRANSLATIONS[lang] || base;

  const raw = getByPath(active, key);
  const fallback = getByPath(base, key);
  const value = raw !== undefined ? raw : fallback !== undefined ? fallback : key;
  return interpolate(value, params);
};

export const useI18n = (overrideLanguage) => {
  const preferencesContext = useContext(PreferencesContext);
  const preferences = preferencesContext?.preferences;

  const preferredLanguage = useMemo(() => {
    if (overrideLanguage) return overrideLanguage;
    return preferences?.uiLanguage ?? preferences?.preferredLanguage;
  }, [overrideLanguage, preferences?.uiLanguage, preferences?.preferredLanguage]);

  const lang = useMemo(
    () => normalizePreferredLanguage(preferredLanguage),
    [preferredLanguage]
  );

  const isSimplified = useMemo(
    () => Boolean(preferences?.simplifiedLayout),
    [preferences?.simplifiedLayout]
  );

  const t = useCallback(
    (key, params) => {
      // EPIC 5.5: If simplified mode is enabled and simplified text exists, use it
      if (isSimplified && lang === 'english') {
        const simplifiedKey = 'simple.' + key.replace(/^learning\./, '');
        const simplifiedText = tFor(lang, simplifiedKey, params);
        // If simplified version exists (not returning the key itself), use it
        if (simplifiedText !== simplifiedKey) {
          return simplifiedText;
        }
      }
      // Fall back to regular translation
      return tFor(lang, key, params);
    },
    [lang, isSimplified]
  );

  return { lang, t, isSimplified };
};
